import { describe, it } from "node:test";
import * as assert from "node:assert/strict";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

import {
  ABI_VERSION,
  BlockType,
  EvalStatus,
  MigrationPolicy,
  RetentionClass,
  SignalQuality,
  WorkerMode,
  decodeEvalRequest,
  decodeEvalResult,
  encodeEvalRequest,
  encodeEvalResult,
  profileHash,
  sha256Hex,
  signBytesEd25519,
  validateRuleSetAgainstProfile,
  verifyModulePackageSignature,
  verifySiteProfileSignature,
  type ModulePackageV1,
  type SiteProfileV1,
} from "./index.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../..");
const demoDir = path.join(repoRoot, "profiles/demo-lyra");

describe("P1 control-abi <-> control-ir cross-verification", () => {
  it("decodes Rust golden EvalRequest and EvalResult and re-encodes byte-for-byte identically", () => {
    const reqBin = new Uint8Array(fs.readFileSync(path.join(demoDir, "golden/eval_request.bin")));
    const resBin = new Uint8Array(fs.readFileSync(path.join(demoDir, "golden/eval_result.bin")));
    const digests = JSON.parse(
      fs.readFileSync(path.join(demoDir, "golden/golden_digests.json"), "utf8")
    ) as { reqSha256: string; resSha256: string; profileHash: string; publicKeyHex: string };

    assert.equal(sha256Hex(reqBin), digests.reqSha256);
    assert.equal(sha256Hex(resBin), digests.resSha256);

    const req = decodeEvalRequest(reqBin);
    assert.equal(req.abiVersion, ABI_VERSION);
    assert.equal(req.mode, WorkerMode.Active);
    assert.equal(req.bootId, 1_777_319_400_000_000_001n);
    assert.equal(req.leaseEpoch, 12n);
    assert.equal(req.scanId, 500n);
    assert.equal(req.signals.length, 2);
    assert.equal(req.signals[0]?.value, 451);
    assert.equal(req.signals[0]?.quality, SignalQuality.Good);
    assert.equal(req.blocks.length, 1);
    assert.equal(req.blocks[0]?.blockType, BlockType.Ton);
    assert.equal(req.blocks[0]?.retentionClass, RetentionClass.Cyclic);
    assert.equal(req.blocks[0]?.migrationPolicy, MigrationPolicy.PreserveElapsed);
    assert.equal(req.blocks[0]?.auxI64, -10n);

    const reEncodedReq = encodeEvalRequest(req);
    assert.deepEqual(reEncodedReq, reqBin);

    const res = decodeEvalResult(resBin);
    assert.equal(res.status, EvalStatus.Ok);
    assert.equal(res.desiredMask, 0x01);
    assert.equal(res.validMask, 0x07);
    const reEncodedRes = encodeEvalResult(res);
    assert.deepEqual(reEncodedRes, resBin);
  });

  it("verifies Ed25519 signatures generated by Rust for site-profile and module-package", () => {
    const pubHex = fs.readFileSync(path.join(demoDir, "keys/test-bench.pub.hex"), "utf8").trim();
    const seedHex = fs.readFileSync(path.join(demoDir, "keys/test-bench.seed.hex"), "utf8").trim();
    const profile = JSON.parse(
      fs.readFileSync(path.join(demoDir, "site-profile.json"), "utf8")
    ) as SiteProfileV1;
    const pkg = JSON.parse(
      fs.readFileSync(path.join(demoDir, "golden/golden_package.json"), "utf8")
    ) as ModulePackageV1;

    assert.equal(verifySiteProfileSignature(profile, pubHex), true);
    assert.equal(verifyModulePackageSignature(pkg, pubHex), true);
    assert.equal(profileHash(profile), pkg.profileHash);

    // Tampered package fails verification
    const tampered = { ...pkg, baseRevision: "42" };
    assert.equal(verifyModulePackageSignature(tampered, pubHex), false);

    // Self-signed check matches
    const sig = signBytesEd25519(seedHex, Buffer.from("plc-test"));
    assert.equal(sig.length, 128);
  });

  it("rejects coercion, unknown fields, free-text outputs, and multiple writers on same channel", () => {
    const profile = JSON.parse(
      fs.readFileSync(path.join(demoDir, "site-profile.json"), "utf8")
    ) as SiteProfileV1;

    const valid = validateRuleSetAgainstProfile(
      {
        schema: "rule-set/v1",
        baseRevision: "41",
        changes: [
          {
            op: "upsertRule",
            ruleId: "temp.high-alarm",
            templateId: "thresholdHoldWithLatchedHysteresis",
            input: "temp.process",
            unit: "degC_x10",
            triggerAtOrAbove: 450,
            clearAtOrBelow: 440,
            holdMs: 10000,
            requiredQuality: "GOOD",
            onInputFault: "COMMAND_OFF_AND_RESET",
            output: "tower.red",
            timingStateOnChange: "RESET",
          },
        ],
      },
      profile
    );
    assert.equal(valid.changes.length, 1);

    // Reject string coercion for number
    assert.throws(() =>
      validateRuleSetAgainstProfile(
        {
          schema: "rule-set/v1",
          baseRevision: "41",
          changes: [
            {
              op: "upsertRule",
              ruleId: "r1",
              templateId: "thresholdHoldWithLatchedHysteresis",
              input: "temp.process",
              unit: "degC_x10",
              triggerAtOrAbove: "450",
              requiredQuality: "GOOD",
              onInputFault: "COMMAND_OFF_AND_RESET",
              output: "tower.red",
              timingStateOnChange: "RESET",
            },
          ],
        },
        profile
      )
    );

    // Reject free-text hardware output binding
    assert.throws(() =>
      validateRuleSetAgainstProfile(
        {
          schema: "rule-set/v1",
          baseRevision: "41",
          changes: [
            {
              op: "upsertRule",
              ruleId: "r1",
              templateId: "thresholdHoldWithLatchedHysteresis",
              input: "temp.process",
              unit: "degC_x10",
              triggerAtOrAbove: 450,
              requiredQuality: "GOOD",
              onInputFault: "COMMAND_OFF_AND_RESET",
              output: "gpiochip0:17",
              timingStateOnChange: "RESET",
            },
          ],
        },
        profile
      )
    );

    // Reject multiple writers on the same channel
    assert.throws(() =>
      validateRuleSetAgainstProfile(
        {
          schema: "rule-set/v1",
          baseRevision: "41",
          changes: [
            {
              op: "upsertRule",
              ruleId: "r1",
              templateId: "thresholdHoldWithLatchedHysteresis",
              input: "temp.process",
              unit: "degC_x10",
              triggerAtOrAbove: 450,
              requiredQuality: "GOOD",
              onInputFault: "COMMAND_OFF_AND_RESET",
              output: "tower.red",
              timingStateOnChange: "RESET",
            },
            {
              op: "upsertRule",
              ruleId: "r2",
              templateId: "thresholdHoldWithLatchedHysteresis",
              input: "temp.process",
              unit: "degC_x10",
              triggerAtOrAbove: 500,
              requiredQuality: "GOOD",
              onInputFault: "COMMAND_OFF_AND_RESET",
              output: "tower.red",
              timingStateOnChange: "RESET",
            },
          ],
        },
        profile
      )
    );
  });
});
